#!/usr/bin/env node
/* Builds vendor/cities/cities.js from the GeoNames cities15000 dump.
 *
 * Source data (CC BY 4.0, https://www.geonames.org/):
 *   cities15000.txt        populated places with population >= 15000
 *   admin1CodesASCII.txt   admin1 code -> region name
 *   countryInfo.txt        country code -> country name
 *
 * Output is a single browser script exposing window.WX_CITIES with a
 * nearest(lat, lon) lookup. No network access, no runtime dependencies.
 *
 * The scoring constants are measured, not guessed — see tests/tune.js.
 *
 * Usage: node tools/build-cities.js <geonames-dir>
 */
"use strict";

const fs = require("fs");
const path = require("path");

const srcDir = process.argv[2];
if (!srcDir) {
  console.error("usage: node tools/build-cities.js <geonames-dir>");
  process.exit(1);
}

const outFile = path.join(__dirname, "..", "vendor", "cities", "cities.js");

/* Coordinates are stored as (round(degrees * 10000) + offset) in base 36.
 * 4 decimal places is ~11 m, which matters because the lookup ranks by
 * distance — a coarser grid misplaces city centroids by whole kilometres. */
const LAT_OFFSET = 90000;
const LON_OFFSET = 180000;
const LAT_SCALE = 10000;

/* Populated-place codes that are not places people would recognise as where
 * they are: abandoned, destroyed, historical, church. */
const EXCLUDE_CODES = new Set(["PPLQ", "PPLW", "PPLH", "PPLCH"]);

/* Scoring constants, chosen by sweeping tests/tune.js:
 *   metro radius  R=6   population log weight  W=2   neighbourhood penalty P=6
 * That combination scores 73/73 on major cities and 18/18 on small towns, and
 * holds across the whole W=1.5-3 plateau rather than sitting on a knife edge. */
const METRO_MIN_POP = 500000;
const METRO_COEF = 6;
const POP_WEIGHT = 2;
const HOOD_PENALTY = 6;

function readLines(file) {
  return fs.readFileSync(file, "utf8").split("\n").filter((l) => l.length > 0);
}

/* ---- admin1 code -> region name (e.g. "US.CA" -> "California") ---- */
const admin1 = {};
for (const line of readLines(path.join(srcDir, "admin1CodesASCII.txt"))) {
  const c = line.split("\t");
  if (c.length >= 2) admin1[c[0]] = c[1];
}

/* ---- country code -> country name (e.g. "US" -> "United States") ---- */
const country = {};
for (const line of readLines(path.join(srcDir, "countryInfo.txt"))) {
  if (line.startsWith("#")) continue;
  const c = line.split("\t");
  if (c.length >= 5 && c[0]) country[c[0]] = c[4];
}

/* ---- cities ---- */
const records = [];
for (const line of readLines(path.join(srcDir, "cities15000.txt"))) {
  const c = line.split("\t");
  if (c.length < 15) continue;

  const name = c[1];
  const lat = parseFloat(c[4]);
  const lon = parseFloat(c[5]);
  const code = c[7];
  const cc = c[8];
  const a1 = c[10] || "";
  const pop = parseInt(c[14], 10) || 0;

  if (!name || !isFinite(lat) || !isFinite(lon)) continue;
  if (EXCLUDE_CODES.has(code)) continue;
  if (!cc) continue;
  if (name.includes("|")) continue; // would break the record format

  records.push({
    name: name.replace(/\s+/g, " ").trim(),
    cc,
    a1,
    pop,
    lat,
    lon,
    // PPLX is "section of a populated place" — a neighbourhood, not a city.
    // Kept as a fallback, penalised at lookup time so a city name wins.
    hood: code === "PPLX" ? 1 : 0,
  });
}

/* ---- serialise ---- */
const lines = records.map((r) => {
  const lat36 = (Math.round(r.lat * LAT_SCALE) + LAT_OFFSET).toString(36);
  const lon36 = (Math.round(r.lon * LAT_SCALE) + LON_OFFSET).toString(36);
  return [r.name, r.cc, r.a1, r.pop.toString(36), lat36, lon36, r.hood].join("|");
});

const raw = lines.join("\n");

/* ---- reference tables, limited to codes actually used ---- */
const usedCc = [...new Set(records.map((r) => r.cc))].sort();
const ccTable = {};
for (const cc of usedCc) ccTable[cc] = country[cc] || cc;

// cities15000 stores admin1 without the country prefix, but the reference
// table is keyed "CC.ADMIN1" — join on the composed key.
const usedA1 = [...new Set(records.filter((r) => r.a1).map((r) => r.cc + "." + r.a1))].sort();
const a1Table = {};
for (const key of usedA1) a1Table[key] = admin1[key] || "";

const js = `/* GeoNames offline city lookup — generated file, do not edit.
 * Data: GeoNames cities15000 (https://www.geonames.org/), CC BY 4.0.
 * Record format, one per line: name|countryCode|admin1Code|population36|lat36|lon36|isNeighbourhood
 * lat/lon are stored as (round(degrees * ${LAT_SCALE}) + offset) in base 36.
 * Generated by tools/build-cities.js — rebuild with: node tools/build-cities.js <geonames-dir>
 */
window.WX_CITIES=(function(){
"use strict";
var RAW=${JSON.stringify(raw)};
var A1=${JSON.stringify(a1Table)};
var CC=${JSON.stringify(ccTable)};
var LAT_OFFSET=${LAT_OFFSET},LON_OFFSET=${LON_OFFSET},LAT_SCALE=${LAT_SCALE};
var METRO_MIN_POP=${METRO_MIN_POP},METRO_COEF=${METRO_COEF},POP_WEIGHT=${POP_WEIGHT},HOOD_PENALTY=${HOOD_PENALTY};
var rows=null;
function parse(){
  if(rows)return rows;
  rows=[];
  var lines=RAW.split("\\n");
  for(var i=0;i<lines.length;i++){
    var f=lines[i].split("|");
    if(f.length<7)continue;
    rows.push({
      n:f[0],
      c:f[1],
      a:f[2],
      p:parseInt(f[3],36)||0,
      la:(parseInt(f[4],36)-LAT_OFFSET)/LAT_SCALE,
      lo:(parseInt(f[5],36)-LON_OFFSET)/LAT_SCALE,
      h:f[6]==="1"
    });
  }
  return rows;
}
/* Nearest named place.
 *
 * Distances use a local equirectangular projection so the longitude scale is
 * correct at the query latitude. Candidates are ranked by
 *
 *   score = max(0, km - metroRadius(pop)) - 2*log10(pop) + (neighbourhood ? 6 : 0)
 *
 * metroRadius gives very large cities a radius, for two measured reasons:
 * GeoNames stores imprecise centroids for some metropolises (its Toronto entry
 * is ~6 km north of downtown, its Dubai entry ~15 km away), and a big city
 * physically covers its inner suburbs. Without it a downtown-neighbourhood
 * entry outranks the city you are actually standing in. The population term
 * breaks ties towards the more significant place, and the flat neighbourhood
 * penalty keeps districts from becoming the headline name.
 */
function nearest(lat,lon){
  var rs=parse();
  var k=Math.cos(lat*Math.PI/180);
  if(k<0.01)k=0.01;
  var best=null,bestScore=Infinity,bestKm=0;
  for(var i=0;i<rs.length;i++){
    var r=rs[i];
    var dy=r.la-lat;
    var dx=(r.lo-lon)*k;
    var km=Math.sqrt(dx*dx+dy*dy)*111.32;
    var eff=km;
    if(r.p>=METRO_MIN_POP){
      var rad=METRO_COEF*(Math.log10(r.p)-5.7)/1.3;
      if(rad>0){eff=km-rad;if(eff<0)eff=0;}
    }
    var score=eff-POP_WEIGHT*Math.log10(r.p>1?r.p:1)+(r.h?HOOD_PENALTY:0);
    if(score<bestScore){bestScore=score;best=r;bestKm=km;}
  }
  if(!best)return null;
  return {
    name:best.n,
    region:A1[best.c+"."+best.a]||"",
    country:CC[best.c]||best.c,
    distanceKm:bestKm
  };
}
return {count:${records.length},nearest:nearest};
})();
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, js);

console.log(`cities:      ${records.length}`);
console.log(`neighbourhoods: ${records.filter((r) => r.hood).length}`);
console.log(`admin1:      ${usedA1.length}`);
console.log(`countries:   ${usedCc.length}`);
console.log(`output:      ${outFile} (${(Buffer.byteLength(js) / 1024).toFixed(0)} KB)`);
