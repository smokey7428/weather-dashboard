#!/bin/bash
# Creates the release signing key for the Android app.
#
# Android identifies an app by its signing key, so this file is the identity of
# the app. If you lose it you cannot ship an update that installs over the copy
# people already have — they would have to uninstall and reinstall, losing their
# saved location. Back it up somewhere durable and private.
#
# The key is self-signed and costs nothing. It is not the same thing as a
# Google Play upload key, and it is not needed to sideload.
#
# Usage: ./make-keystore.sh [--force]
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ANDROID_DIR="$(dirname "$HERE")"
KS_DIR="$ANDROID_DIR/keystore"
KEYSTORE="$KS_DIR/weatherdashboard.jks"
PROPS="$ANDROID_DIR/keystore.properties"

JAVA_HOME="${JAVA_HOME:-$HOME/Library/Android/jdk17/Contents/Home}"
KEYTOOL="$JAVA_HOME/bin/keytool"

ALIAS="weatherdashboard"
VALIDITY_DAYS=10000   # ~27 years; Play requires the key to outlive the app

if [ ! -x "$KEYTOOL" ]; then
  echo "error: keytool not found at $KEYTOOL" >&2
  echo "set JAVA_HOME, or run tools/bootstrap-toolchain.sh first" >&2
  exit 1
fi

print_fingerprint() {
  echo "certificate fingerprint (share this so people can verify the APK):"
  "$KEYTOOL" -list -v -keystore "$KEYSTORE" -storepass "$PASSWORD" -alias "$ALIAS" \
    | grep -E 'SHA-?256|Valid from' || true
}

if [ -f "$KEYSTORE" ]; then
  PASSWORD="$(grep '^storePassword=' "$PROPS" 2>/dev/null | cut -d= -f2- || true)"
  if [ -z "$PASSWORD" ]; then
    echo "keystore exists at $KEYSTORE but $PROPS is missing or unreadable." >&2
    echo "Without the password the key cannot be used to sign anything." >&2
    exit 1
  fi
  if [ "$#" -eq 0 ]; then
    echo "keystore already exists: $KEYSTORE"
    echo
    print_fingerprint
    echo
    echo "re-run with --force to replace it (this changes the app's identity)"
    exit 0
  fi
fi

# A random password is better than a memorable one here: it never needs to be
# typed by a human, and it is stored in keystore.properties (git-ignored).
# (Avoid `tr < /dev/urandom | head`: pipefail turns the resulting SIGPIPE into
# a script failure.)
PASSWORD="$(openssl rand -hex 20)"

mkdir -p "$KS_DIR"

"$KEYTOOL" -genkeypair -v \
  -keystore "$KEYSTORE" \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize 4096 \
  -validity "$VALIDITY_DAYS" \
  -storepass "$PASSWORD" \
  -keypass "$PASSWORD" \
  -dname "CN=Weather Dashboard, OU=Weather Dashboard, O=Weather Dashboard, L=, ST=, C="

chmod 600 "$KEYSTORE"

cat > "$PROPS" <<EOF
# Generated by tools/make-keystore.sh — do not commit.
# Path is relative to the android/ Gradle root.
storeFile=keystore/weatherdashboard.jks
storePassword=$PASSWORD
keyAlias=$ALIAS
keyPassword=$PASSWORD
EOF
chmod 600 "$PROPS"

echo
echo "keystore:   $KEYSTORE"
echo "properties: $PROPS"
echo
print_fingerprint
echo
echo "Back up $KEYSTORE and $PROPS now. Without them you cannot sign an update"
echo "that installs over this one."
